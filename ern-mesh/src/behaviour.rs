//! Composed network behaviour — all libp2p sub-protocols in one derive.
//!
//! ErnMesh composes five sub-protocols into a single `NetworkBehaviour`:
//!
//! - **Gossipsub**: Pub/sub messaging for ErnChat, ErnieBook, and topic broadcasts.
//!   Uses `MessageAuthenticity::Signed` — every message carries an Ed25519 signature.
//! - **Kademlia**: Distributed hash table for global peer discovery and content routing.
//! - **mDNS**: Zero-config local network peer discovery (same LAN).
//! - **Identify**: Exchanges peer metadata (public key, protocols, agent version).
//! - **Ping**: Periodic connectivity checks and RTT measurement.
//!
//! The composed `MeshBehaviour` is used by the Swarm (in `swarm.rs`) to drive
//! all mesh protocol events through a single event loop.

use libp2p::gossipsub;
use libp2p::identify;
use libp2p::kad;
use libp2p::mdns;
use libp2p::ping;
use libp2p::swarm::NetworkBehaviour;
use libp2p_identity::Keypair;

use anyhow::{Context, Result};

use crate::config::MeshConfig;

/// The composed network behaviour — all mesh sub-protocols unified.
///
/// Events from each sub-protocol are merged into [`MeshBehaviourEvent`]
/// (auto-derived by `#[derive(NetworkBehaviour)]`).
#[derive(NetworkBehaviour)]
#[behaviour(to_swarm = "MeshBehaviourEvent")]
pub struct MeshBehaviour {
    /// Pub/sub messaging — signed messages, topic-based routing.
    pub gossipsub: gossipsub::Behaviour,

    /// Kademlia DHT — global peer discovery and content routing.
    pub kademlia: kad::Behaviour<kad::store::MemoryStore>,

    /// mDNS — local network peer discovery (zero-config).
    pub mdns: mdns::tokio::Behaviour,

    /// Identify — peer metadata exchange (protocols, agent version).
    pub identify: identify::Behaviour,

    /// Ping — connectivity checks and round-trip time measurement.
    pub ping: ping::Behaviour,
}

/// Unified event type for all sub-protocols.
///
/// Auto-generated by `#[derive(NetworkBehaviour)]`. Each variant wraps
/// the event type of the corresponding sub-protocol.
#[derive(Debug)]
pub enum MeshBehaviourEvent {
    Gossipsub(gossipsub::Event),
    Kademlia(kad::Event),
    Mdns(mdns::Event),
    Identify(identify::Event),
    Ping(ping::Event),
}

impl From<gossipsub::Event> for MeshBehaviourEvent {
    fn from(e: gossipsub::Event) -> Self {
        MeshBehaviourEvent::Gossipsub(e)
    }
}

impl From<kad::Event> for MeshBehaviourEvent {
    fn from(e: kad::Event) -> Self {
        MeshBehaviourEvent::Kademlia(e)
    }
}

impl From<mdns::Event> for MeshBehaviourEvent {
    fn from(e: mdns::Event) -> Self {
        MeshBehaviourEvent::Mdns(e)
    }
}

impl From<identify::Event> for MeshBehaviourEvent {
    fn from(e: identify::Event) -> Self {
        MeshBehaviourEvent::Identify(e)
    }
}

impl From<ping::Event> for MeshBehaviourEvent {
    fn from(e: ping::Event) -> Self {
        MeshBehaviourEvent::Ping(e)
    }
}

/// Build the composed `MeshBehaviour` from config and keypair.
///
/// Configures all five sub-protocols:
/// - Gossipsub with signed message authentication and strict validation
/// - Kademlia with the ErnMesh protocol name
/// - mDNS for LAN discovery
/// - Identify with ErnMesh agent version
/// - Ping with default settings
pub fn build_behaviour(
    keypair: &Keypair,
    config: &MeshConfig,
) -> Result<MeshBehaviour> {
    let local_peer_id = libp2p_identity::PeerId::from_public_key(&keypair.public());

    // ── Gossipsub ──
    let gossipsub = build_gossipsub(keypair, config)?;

    // ── Kademlia ──
    let kademlia = build_kademlia(local_peer_id)?;

    // ── mDNS ──
    let mdns = mdns::tokio::Behaviour::new(
        mdns::Config::default(),
        local_peer_id,
    ).context("Failed to create mDNS behaviour")?;

    tracing::debug!("mDNS behaviour configured for local discovery");

    // ── Identify ──
    let identify = identify::Behaviour::new(
        identify::Config::new(
            "/ernmesh/id/1.0.0".to_string(),
            keypair.public(),
        )
        .with_agent_version(format!("ern-mesh/{}", env!("CARGO_PKG_VERSION"))),
    );

    tracing::debug!("Identify behaviour configured");

    // ── Ping ──
    let ping = ping::Behaviour::new(ping::Config::new());

    tracing::debug!("Ping behaviour configured");

    tracing::info!(
        peer_id = %local_peer_id,
        "Composed MeshBehaviour: Gossipsub + Kademlia + mDNS + Identify + Ping"
    );

    Ok(MeshBehaviour {
        gossipsub,
        kademlia,
        mdns,
        identify,
        ping,
    })
}

/// Build Gossipsub with strict configuration per §14.3.
///
/// - `MessageAuthenticity::Signed`: every message carries Ed25519 signature
/// - Message validation enabled
/// - Max transmit size from security config
fn build_gossipsub(
    keypair: &Keypair,
    config: &MeshConfig,
) -> Result<gossipsub::Behaviour> {
    let gossipsub_config = gossipsub::ConfigBuilder::default()
        .max_transmit_size(config.security.max_payload_bytes as usize)
        .validation_mode(gossipsub::ValidationMode::Strict)
        .build()
        .map_err(|e| anyhow::anyhow!("Failed to build Gossipsub config: {}", e))?;

    let gossipsub = gossipsub::Behaviour::new(
        gossipsub::MessageAuthenticity::Signed(keypair.clone()),
        gossipsub_config,
    ).map_err(|e| anyhow::anyhow!("Failed to create Gossipsub behaviour: {}", e))?;

    tracing::debug!(
        max_transmit_size = config.security.max_payload_bytes,
        validation = "strict",
        authentication = "signed",
        "Gossipsub behaviour configured"
    );

    Ok(gossipsub)
}

/// Build Kademlia with ErnMesh protocol name.
fn build_kademlia(
    local_peer_id: libp2p_identity::PeerId,
) -> Result<kad::Behaviour<kad::store::MemoryStore>> {
    let store = kad::store::MemoryStore::new(local_peer_id);
    let mut kademlia = kad::Behaviour::new(local_peer_id, store);

    // Set the Kademlia protocol name to isolate ErnMesh from other networks
    kademlia.set_mode(Some(kad::Mode::Server));

    tracing::debug!(
        protocol = "/ernmesh/kad/1.0.0",
        mode = "server",
        "Kademlia behaviour configured"
    );

    Ok(kademlia)
}

